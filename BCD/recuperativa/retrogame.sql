DROP DATABASE RECUPERATIVA_RETROGAME_VINICIUS;
CREATE DATABASE RECUPERATIVA_RETROGAME_VINICIUS;
USE RECUPERATIVA_RETROGAME_VINICIUS;

CREATE TABLE CLIENTE (
    ID_CLIENTE INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL,
    TELEFONE VARCHAR(20) NULL,
    ATIVO BOOLEAN DEFAULT TRUE,

    CONSTRAINT UQ_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE PLATAFORMA (
    ID_PLATAFORMA INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(80) NOT NULL,

    CONSTRAINT UQ_PLATAFORMA_NOME UNIQUE (NOME)
);

CREATE TABLE CATEGORIA (
    ID_CATEGORIA INT PRIMARY KEY AUTO_INCREMENT,
    DESCRICAO VARCHAR(80) NOT NULL,

    CONSTRAINT UQ_CATEGORIA_DESCRICAO UNIQUE (DESCRICAO)
);

CREATE TABLE JOGO (
    ID_JOGO INT PRIMARY KEY AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL,
    CODIGO VARCHAR(120) NOT NULL,
    ANO_LANCAMENTO INT NOT NULL,
    QUANTIDADE_DISPONIVEL INT DEFAULT 0,
    ID_CATEGORIA INT NOT NULL,
    ID_PLATAFORMA INT NOT NULL,

    CONSTRAINT UQ_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CHK_ESTOQUE CHECK (QUANTIDADE_DISPONIVEL >= 0),
    CONSTRAINT FK_JOGO_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA (ID_CATEGORIA),
    CONSTRAINT FK_JOGO_PLATAFORMA FOREIGN KEY (ID_PLATAFORMA) REFERENCES PLATAFORMA (ID_PLATAFORMA)
);

CREATE TABLE LOCACAO (
    ID_LOCACAO INT PRIMARY KEY AUTO_INCREMENT,
    DATA_RETIRADA DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE NULL,
    STATUS_LOCACAO VARCHAR(20) DEFAULT 'ABERTA',
    ID_CLIENTE INT NOT NULL,
    ID_JOGO INT NOT NULL,

    CONSTRAINT CHK_LOCACAO_STATUS CHECK (STATUS_LOCACAO IN ('ABERTA', 'DEVOLVIDA', 'ATRASADA')),
    CONSTRAINT FK_LOCACAO_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE (ID_CLIENTE) ON DELETE RESTRICT,
    CONSTRAINT FK_LOCACAO_JOGO FOREIGN KEY (ID_JOGO) REFERENCES JOGO (ID_JOGO) ON DELETE RESTRICT
);


